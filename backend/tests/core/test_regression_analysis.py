def _load_fixture_table(base_path: Path, columns: list[str]) -> pd.DataFrame:
    """
    Load legacy whitespace-separated fixture tables
    Supports both uncompressed (.txt) and gzip-compressed (.txt.gz) variants
    """
    gz_path = base_path.with_name(f"{base_path.name}.txt.gz")
    txt_path = base_path.with_name(f"{base_path.name}.txt")
    
    # Prefer .txt.gz if present to save disk space; fallback to .txt
    target_path = gz_path if gz_path.exists() else txt_path

    if not target_path.exists():
        raise FileNotFoundError(f"Fixture not found: neither {gz_path} nor {txt_path} exist.")

    # Legacy routines format tables with variable whitespace separators (spaces/tabs)
    df = pd.read_csv(target_path, sep=r"\s+", engine="python")
    
    # Overwrite column headers to match the pipeline's output schema
    if columns:
        df.columns = columns
    return df


